#!/usr/bin/env python3
"""T2 — Telegram webhook to a LOCAL customer bot, without Render (CLM-0635 · ADR-073).

Prepares and guards the procedure in docs/12-testing/T2_LOCAL_WEBHOOK_PROCEDURE.md:
customer-bot + identity run on this machine against a throw-away PostgreSQL bound to
127.0.0.1, with test-only keys generated here, reached by Telegram through an HTTPS
tunnel. Nothing here talks to Render or to the production database.

  init     DIR              generate DIR/{identity.env,bot.env,pg.env} (mode 600); keys are new, test-only
  preflight DIR             refuse unless every value is local and test-only (never prints a value)
  probe    URL DIR          POST the public webhook URL without / with a wrong secret → both must be 401
  register URL DIR          setWebhook — REFUSED unless test_plan_items.T2 is approved in
                            infra/render/deploy-target.json (owner approval) and preflight passes
  info     DIR              getWebhookInfo (read-only) — same approval rule
  self-test                 offline negative cases; no network, no Telegram

Limits: preflight proves the configuration points at a local database and carries keys
generated by `init` (kid prefix t2test-); it cannot prove the bot token is a test token
(owner statement) and cannot compare against production secrets (none exist yet).
"""
from __future__ import annotations

import json
import os
import re
import secrets
import string
import sys
import tempfile
import urllib.parse
import urllib.request

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
TARGET = os.path.join(ROOT, "infra", "render", "deploy-target.json")
LOCAL_HOSTS = {"127.0.0.1", "localhost", "::1"}
KID_PREFIX = "t2test-"
SECRET_RE = re.compile(r"^[A-Za-z0-9_-]{16,256}$")  # Telegram secret_token charset · MIN_WEBHOOK_SECRET_LENGTH 16
TOKEN_RE = re.compile(r"^\d{6,12}:[A-Za-z0-9_-]{30,}$")
IDENTITY_PORT, BOT_PORT, PG_PORT = 18080, 18083, 55432
WEBHOOK_PATH = "/channel/customer/webhook"


def _rand(n: int) -> str:
    return "".join(secrets.choice(string.ascii_letters + string.digits + "_-") for _ in range(n))


def read_env(path: str) -> dict[str, str]:
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def write_env(path: str, kv: dict[str, str]) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        for k, v in kv.items():
            f.write(f"{k}={v}\n")


def init(d: str) -> None:
    os.makedirs(d, mode=0o700, exist_ok=True)
    kid = f"{KID_PREFIX}{_rand(8).lower().replace('_', 'x').replace('-', 'y')}"
    service_key = f"{kid}:active:{_rand(48)}"
    pg_pw = _rand(32).replace("-", "x").replace("_", "y")
    db = f"postgresql://wasla_t2:{pg_pw}@127.0.0.1:{PG_PORT}/wasla_t2"
    common = {"NODE_ENV": "development", "WASLA_SERVICE_AUTH_KEYS": service_key, "WASLA_SERVICE_AUTH_ACTIVE_KID": kid,
              "WASLA_USER_ASSERTION_MODE": "off"}
    write_env(os.path.join(d, "pg.env"), {"POSTGRES_USER": "wasla_t2", "POSTGRES_PASSWORD": pg_pw, "POSTGRES_DB": "wasla_t2"})
    write_env(os.path.join(d, "identity.env"), {**common, "PORT": str(IDENTITY_PORT), "DATABASE_URL": db})
    # The bot's service-token replay store lives in the same local database (as on Render).
    write_env(os.path.join(d, "bot.env"), {**common, "CUSTOMER_BOT_PORT": str(BOT_PORT), "DATABASE_URL": db,
              "IDENTITY_SERVICE_URL": f"http://127.0.0.1:{IDENTITY_PORT}",
              "CUSTOMER_BOT_TOKEN": "", "CUSTOMER_BOT_WEBHOOK_SECRET": _rand(48),
              "CUSTOMER_BOT_MINI_APP_URL": "https://t2-no-mini-app.invalid/"})
    print(f"T2 files written to {d} (mode 600). Put the owner's TEST bot token in bot.env CUSTOMER_BOT_TOKEN; values are not printed.")


def production_refs() -> list[str]:
    t = json.load(open(TARGET, encoding="utf-8"))
    return list(t.get("production_database_refs") or []) + ["pvyuhjadrygqqdoczmnd"]  # + the DR project


def preflight_findings(identity: dict, bot: dict, refs: list[str]) -> list[str]:
    """Names only — never a value."""
    f = []
    for name, env in (("identity.env", identity), ("bot.env", bot)):
        if env.get("NODE_ENV") == "production":
            f.append(f"{name}: NODE_ENV=production")
        for k, v in env.items():
            if k.endswith("DATABASE_URL") and v:
                u = urllib.parse.urlparse(v)
                if (u.hostname or "") not in LOCAL_HOSTS:
                    f.append(f"{name}: {k} is not a local database (host must be 127.0.0.1/localhost)")
                if any(r in v for r in refs) or "supabase" in v:
                    f.append(f"{name}: {k} points at a Supabase/production project")
            if k.endswith("_URL") and v and ("onrender.com" in v or "supabase" in v):
                f.append(f"{name}: {k} points at a hosted (Render/Supabase) endpoint")
        keys = env.get("WASLA_SERVICE_AUTH_KEYS", "")
        kids = [e.split(":", 1)[0] for e in keys.split(",") if e.strip()]
        if not kids or any(not k.startswith(KID_PREFIX) for k in kids):
            f.append(f"{name}: WASLA_SERVICE_AUTH_KEYS must hold only {KID_PREFIX}* keys generated by `init`")
        if env.get("WASLA_USER_ASSERTION_SIGNING_KEY"):
            f.append(f"{name}: WASLA_USER_ASSERTION_SIGNING_KEY must be empty for T2 (T1 is deferred)")
    if not identity.get("DATABASE_URL"):
        f.append("identity.env: DATABASE_URL missing (local PostgreSQL required)")
    if not bot.get("DATABASE_URL") and bot.get("WASLA_SERVICE_TOKEN_REPLAY_MODE") != "memory":
        f.append("bot.env: DATABASE_URL missing (the service-token replay store needs the local PostgreSQL)")
    if identity.get("WASLA_SERVICE_AUTH_KEYS") != bot.get("WASLA_SERVICE_AUTH_KEYS"):
        f.append("bot.env and identity.env must share the same T2 service-auth key")
    if (urllib.parse.urlparse(bot.get("IDENTITY_SERVICE_URL", "")).hostname or "") not in LOCAL_HOSTS:
        f.append("bot.env: IDENTITY_SERVICE_URL must be the local identity service")
    if not TOKEN_RE.match(bot.get("CUSTOMER_BOT_TOKEN", "")):
        f.append("bot.env: CUSTOMER_BOT_TOKEN missing or not a bot token")
    if not SECRET_RE.match(bot.get("CUSTOMER_BOT_WEBHOOK_SECRET", "")):
        f.append("bot.env: CUSTOMER_BOT_WEBHOOK_SECRET must be 16–256 chars of [A-Za-z0-9_-]")
    return f


def preflight(d: str) -> int:
    f = preflight_findings(read_env(os.path.join(d, "identity.env")), read_env(os.path.join(d, "bot.env")), production_refs())
    for x in f:
        print(f"preflight: {x}")
    print("preflight: PASS — local database, T2-only keys, webhook secret present (values not printed)" if not f else f"preflight: FAIL ({len(f)})")
    return 1 if f else 0


def t2_approval(target_path: str = TARGET) -> str | None:
    t = json.load(open(target_path, encoding="utf-8"))
    item = (t.get("test_plan_items") or {}).get("T2") or {}
    ref = str(item.get("approval") or "").strip()
    return ref if item.get("approved") is True and ref else None


def check_public_url(url: str) -> str | None:
    u = urllib.parse.urlparse(url)
    if u.scheme != "https" or not u.hostname:
        return "the webhook URL must be https://"
    if u.hostname.endswith("onrender.com") or u.hostname in LOCAL_HOSTS:
        return "the webhook URL must be the HTTPS tunnel to this machine, not Render or localhost"
    return None


def telegram(token: str, method: str, params: dict) -> dict:
    req = urllib.request.Request(f"https://api.telegram.org/bot{token}/{method}",
                                 data=json.dumps(params).encode(), headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def guarded(d: str, url: str | None, target_path: str = TARGET) -> tuple[dict | None, str | None]:
    if not t2_approval(target_path):
        return None, "T2 is not approved: infra/render/deploy-target.json test_plan_items.T2.approved/approval (owner decision) — nothing sent to Telegram"
    if url is not None and (e := check_public_url(url)):
        return None, e
    bot = read_env(os.path.join(d, "bot.env"))
    f = preflight_findings(read_env(os.path.join(d, "identity.env")), bot, production_refs())
    if f:
        return None, f"preflight failed ({len(f)}): " + "; ".join(f)
    return bot, None


def register(url: str, d: str) -> int:
    bot, err = guarded(d, url)
    if err:
        print(f"register: REFUSED — {err}")
        return 1
    hook = url.rstrip("/") + WEBHOOK_PATH
    r = telegram(bot["CUSTOMER_BOT_TOKEN"], "setWebhook", {"url": hook, "secret_token": bot["CUSTOMER_BOT_WEBHOOK_SECRET"],
                                                          "allowed_updates": ["message", "callback_query"], "drop_pending_updates": True})
    print(f"register: setWebhook ok={r.get('ok')} url={hook}")
    return 0 if r.get("ok") else 1


def info(d: str) -> int:
    bot, err = guarded(d, None)
    if err:
        print(f"info: REFUSED — {err}")
        return 1
    r = telegram(bot["CUSTOMER_BOT_TOKEN"], "getWebhookInfo", {}).get("result", {})
    print(json.dumps({k: r.get(k) for k in ("url", "pending_update_count", "last_error_date", "last_error_message", "has_custom_certificate")}, indent=1))
    return 0


def probe(url: str, d: str) -> int:
    if e := check_public_url(url):
        print(f"probe: REFUSED — {e}")
        return 1
    hook = url.rstrip("/") + WEBHOOK_PATH
    body = json.dumps({"update_id": 1}).encode()
    bad = 0
    for label, headers in (("no secret header", {}), ("wrong secret header", {"X-Telegram-Bot-Api-Secret-Token": _rand(32)})):
        req = urllib.request.Request(hook, data=body, headers={"Content-Type": "application/json", **headers})
        try:
            code = urllib.request.urlopen(req, timeout=15).status
        except urllib.error.HTTPError as e:
            code = e.code
        ok = code == 401
        bad += not ok
        print(f"probe: {label}: HTTP {code} {'✓ rejected' if ok else '✗ expected 401'}")
    return 1 if bad else 0


def self_test() -> int:
    fails = []
    secret_marker = "NEVER-PRINT-" + _rand(12)
    with tempfile.TemporaryDirectory() as d:
        init(os.path.join(d, "t2"))
        base = os.path.join(d, "t2")
        ident, bot = read_env(os.path.join(base, "identity.env")), read_env(os.path.join(base, "bot.env"))
        bot["CUSTOMER_BOT_TOKEN"] = "123456789:" + "A" * 35
        refs = ["abcdefghijklmnopqrst"]
        got = preflight_findings(ident, bot, refs)
        if got:
            fails.append(f"S1 generated configuration should pass, got {got}")
        s1 = f"  {'✓' if not got else '✗'} S1 control: configuration generated by init passes preflight"
        cases = [
            ("S2", "DATABASE_URL on the production project", {"DATABASE_URL": f"postgresql://postgres.abcdefghijklmnopqrst:{secret_marker}@127.0.0.1:5432/postgres"}, {}, "Supabase/production"),
            ("S3", "DATABASE_URL on a remote host", {"DATABASE_URL": f"postgresql://u:{secret_marker}@aws-0-ap-south-1.pooler.supabase.com:6543/postgres"}, {}, "not a local database"),
            ("S4", "webhook secret too short", {}, {"CUSTOMER_BOT_WEBHOOK_SECRET": "short"}, "WEBHOOK_SECRET"),
            ("S5", "webhook secret with a forbidden character", {}, {"CUSTOMER_BOT_WEBHOOK_SECRET": "a" * 20 + "!"}, "WEBHOOK_SECRET"),
            ("S6", "bot token missing", {}, {"CUSTOMER_BOT_TOKEN": ""}, "CUSTOMER_BOT_TOKEN"),
            ("S7", "NODE_ENV=production", {"NODE_ENV": "production"}, {}, "NODE_ENV=production"),
            ("S8", "a reused (non-T2) service-auth key", {"WASLA_SERVICE_AUTH_KEYS": f"prod-1:active:{secret_marker}"}, {"WASLA_SERVICE_AUTH_KEYS": f"prod-1:active:{secret_marker}"}, "t2test-"),
            ("S9", "identity URL on Render", {}, {"IDENTITY_SERVICE_URL": "https://wasla-identity.onrender.com"}, "hosted"),
            ("S10", "another *_DATABASE_URL remote", {}, {"CUSTOMER_DATABASE_URL": f"postgresql://u:{secret_marker}@db.example.com/x"}, "CUSTOMER_DATABASE_URL is not a local"),
            ("S11", "a signing key present (T1 material)", {"WASLA_USER_ASSERTION_SIGNING_KEY": f"k1:{secret_marker}"}, {}, "SIGNING_KEY must be empty"),
        ]
        lines = [s1]
        for cid, desc, di, db_, frag in cases:
            got = preflight_findings({**ident, **di}, {**bot, **db_}, refs)
            ok = any(frag in x for x in got) and not any(secret_marker in x for x in got)
            lines.append(f"  {'✓' if ok else '✗'} {cid} {desc}: {'refused — ' + next((x for x in got if frag in x), '') if ok else got}")
            if not ok:
                fails.append(f"{cid} {desc}: {got}")
        # register/info refused while T2 is not approved — no network allowed
        real_urlopen = urllib.request.urlopen
        net = []
        urllib.request.urlopen = lambda *a, **k: net.append(a) or (_ for _ in ()).throw(RuntimeError("network used"))
        try:
            tgt = os.path.join(d, "target.json")
            json.dump({"production_database_refs": refs, "test_plan_items": {"T2": {"approved": False, "approval": None}}}, open(tgt, "w"))
            _, err = guarded(base, "https://abc.trycloudflare.com", tgt)
            ok = bool(err) and "not approved" in err and not net
            lines.append(f"  {'✓' if ok else '✗'} S12 register while T2 is not approved: {'refused, 0 network calls' if ok else err}")
            if not ok: fails.append("S12 register not refused while T2 unapproved")
            json.dump({"production_database_refs": refs, "test_plan_items": {"T2": {"approved": True, "approval": "docs/x.md"}}}, open(tgt, "w"))
            for cid, url, frag in (("S13", "http://abc.trycloudflare.com", "https://"), ("S14", "https://wasla-customer-bot.onrender.com", "not Render")):
                _, err = guarded(base, url, tgt)
                ok = bool(err) and frag in err and not net
                lines.append(f"  {'✓' if ok else '✗'} {cid} register to {url.split('//')[0]}//{urllib.parse.urlparse(url).hostname.split('.')[-2]}…: {'refused, 0 network calls' if ok else err}")
                if not ok: fails.append(f"{cid} not refused")
            _, err = guarded(base, "https://abc.trycloudflare.com", tgt)  # approved but token empty in the files → preflight
            ok = bool(err) and "CUSTOMER_BOT_TOKEN" in err and not net
            lines.append(f"  {'✓' if ok else '✗'} S15 approved but preflight failing (no token in bot.env): {'refused, 0 network calls' if ok else err}")
            if not ok: fails.append("S15 not refused")
            if read_env(os.path.join(base, "bot.env"))["CUSTOMER_BOT_WEBHOOK_SECRET"] in "".join(lines):
                fails.append("a secret value was printed")
        finally:
            urllib.request.urlopen = real_urlopen
        mode = oct(os.stat(os.path.join(base, "bot.env")).st_mode & 0o777)
        if mode != "0o600":
            fails.append(f"bot.env mode {mode}, expected 0o600")
        lines.append(f"  {'✓' if mode == '0o600' else '✗'} S16 generated files are mode 600: {mode}")
    print("T2 local procedure self-test (offline):")
    print("\n".join(lines))
    for f in fails:
        print(f"  ✗ {f}")
    print(f"  {'✓' if not fails else '✗'} T2 self-test: {16 - len(fails)}/16")
    return 1 if fails else 0


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    cmd, rest = argv[0], argv[1:]
    d = lambda i: os.path.expanduser(rest[i]) if len(rest) > i else os.path.expanduser("~/.wasla-t2")
    if cmd == "init": init(d(0)); return 0
    if cmd == "preflight": return preflight(d(0))
    if cmd == "probe": return probe(rest[0], d(1))
    if cmd == "register": return register(rest[0], d(1))
    if cmd == "info": return info(d(0))
    if cmd == "self-test": return self_test()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
