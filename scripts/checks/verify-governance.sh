#!/usr/bin/env bash
# verify-governance.sh — المدخل الموحّد لكل فحوص الحوكمة. أمر واحد يُشغّله البشري والوكيل وCI.
#
# الفحوص: 0) وجود الوثائق · 1) اللوحة · 2) الحجوزات · 3) التوثيق مع الدفع ·
#         4) بياتُ الحجوزات (M0-16) · 5) هدفُ طلبِ الدمج (M0-17) · 6) الأسرار ·
#         7) عزلُ DDL في اختباراتِ التكامل (M0-03) · 8) CI مانعٌ لا مُجمِّل (M0-04) · …
#         26) STATE-SYNC (M0-52) · 27) الدمجُ يُغلِقُ الدورة (M0-52) — docs/00-rules/STATE_SYNC_RULE.md ·
#         28) edge-allowlist-guard (ADR-069 §2.8 · CLM-0521) — docs/12-testing/EDGE_ALLOWLIST.md.
#
# وليست هذه البوّابةُ المدخلَ الأعلى بعدَ M0-04: `scripts/verify.sh` يُشغّلُها
# ومعها بنيةُ المستودعِ والأنواعُ والاختباراتُ، ويكتبُ أرتفاكتاً (VERIFY_COMMAND.md).
#
#   bash scripts/checks/verify-governance.sh              # يقارن origin/main..HEAD
#   bash scripts/checks/verify-governance.sh OLD NEW      # نطاق صريح (CI)
#   GOVERNANCE_LEDGER_ONLY=1 bash scripts/checks/verify-governance.sh   # سلامة السجلات فقط، بلا git
#
# المرجع: docs/16-progress/README.md · docs/00-rules/WORK_CLAIM_RULE.md
set -uo pipefail

cd "$(dirname "$0")/../.." || { echo "تعذّر الوصول إلى جذر المستودع" >&2; exit 1; }

OLD="${1:-origin/main}"
NEW="${2:-HEAD}"
LEDGER_ONLY="${GOVERNANCE_LEDGER_ONLY:-0}"

BOLD=$'\033[1m'; RED=$'\033[31m'; GRN=$'\033[32m'; YLW=$'\033[33m'; DIM=$'\033[2m'; RST=$'\033[0m'

FAILED=()
PASSED=()
SKIPPED=()

hdr() { printf '\n%s──── %s ────%s\n' "$DIM" "$1" "$RST"; }

run_check() { # run_check <اسم> <أمر...>
  local name="$1"; shift
  hdr "$name"
  if "$@"; then
    PASSED+=("$name")
  else
    FAILED+=("$name")
  fi
}

printf '%s╔══════════════════════════════════════════════════════════╗%s\n' "$BOLD" "$RST"
printf '%s║  فحص حوكمة WASLA — بوابة واحدة لكل الفحوص                ║%s\n' "$BOLD" "$RST"
printf '%s╚══════════════════════════════════════════════════════════╝%s\n' "$BOLD" "$RST"

# ── 0) وجود الوثائق الحاكمة ─────────────────────────────────────────────
# القائمةُ **لا تُكتب هنا**: كانت نسخةً ثانيةً تفارق كتلةَ CI المضمَّنةَ في 12
# عنصراً (M0-04). المصدرُ الواحدُ: scripts/checks/lib/required-artifacts.sh —
# فما تُلزمه البوّابةُ محلّياً تُلزمه CI بعينِه، والعكس.
hdr "0) وجود الوثائق الحاكمة"
# shellcheck source=lib/required-artifacts.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/required-artifacts.sh"
MISSING_DOCS=()
for d in "${REQUIRED_DOCS[@]}"; do
  if [[ -f "$d" ]]; then printf '  %s✓%s %s\n' "$GRN" "$RST" "$d"
  else printf '  %s✗%s %s\n' "$RED" "$RST" "$d"; MISSING_DOCS+=("$d"); fi
done
if (( ${#MISSING_DOCS[@]} )); then FAILED+=("وجود الوثائق الحاكمة"); else PASSED+=("وجود الوثائق الحاكمة"); fi

# ── 1) بنية اللوحة ──────────────────────────────────────────────────────
run_check "1) بنية لوحة التنفيذ" \
  bash scripts/checks/validate-launch-board.sh docs/16-progress/LAUNCH_EXECUTION_BOARD.md

# ── 2) حجوزات العمل ─────────────────────────────────────────────────────
IN_GIT=0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 && IN_GIT=1

if (( IN_GIT )) && [[ "$LEDGER_ONLY" != "1" ]] && git rev-parse --verify "${OLD}^{commit}" >/dev/null 2>&1; then
  run_check "2) حجوزات العمل (سجل + ملفات مُعدّلة)" \
    bash scripts/checks/validate-work-claims.sh "$OLD" "$NEW"
else
  run_check "2) حجوزات العمل (سلامة السجل فقط)" \
    bash scripts/checks/validate-work-claims.sh
fi

# ── 3) قاعدة التوثيق مع الدفع ───────────────────────────────────────────
if (( IN_GIT )) && [[ "$LEDGER_ONLY" != "1" ]]; then
  if git rev-parse --verify "${OLD}^{commit}" >/dev/null 2>&1; then
    run_check "3) قاعدة التوثيق مع الدفع" \
      bash scripts/checks/require-doc-update.sh "$OLD" "$NEW"
  else
    hdr "3) قاعدة التوثيق مع الدفع"
    printf '  %s⊘ تخطٍّ:%s تعذّر حل «%s». نفّذ: git fetch origin main\n' "$YLW" "$RST" "$OLD"
    SKIPPED+=("3) قاعدة التوثيق مع الدفع — مرجع غير قابل للحل")
  fi
else
  hdr "3) قاعدة التوثيق مع الدفع"
  printf '  %s⊘ تخطٍّ:%s لا مستودع git، أو وضع «السجلات فقط».\n' "$YLW" "$RST"
  SKIPPED+=("3) قاعدة التوثيق مع الدفع — لا سياق git")
fi

# ── 4) بياتُ الحجوزات (M0-16) ───────────────────────────────────────────
# لا يُحتاج git range هنا: السؤالُ عن **وجودِ فرعٍ** لا عن فرقِ التزامَين. وإن
# تعذّر السؤالُ يُعلن الفحصُ تخطّيه في مخرجِه ويخرج بـ0 — فالجهلُ ليس دليلَ بيات.
# ولا يُحتسَب نجاحاً كاملاً ما كان جزئيّاً: إن أعلن الفحصُ تخطّيه أُضيف إلى
# «تُخطّي» لا إلى «نجح» — وإلّا كانت البوّابةُ تُجمِّل مخرجَ فحصٍ لم يفحص.
if [[ -f scripts/checks/validate-claim-freshness.sh ]]; then
  hdr "4) بياتُ الحجوزات (فرعٌ محذوفٌ وحجزٌ نشط)"
  FRESH_OUT="$(bash scripts/checks/validate-claim-freshness.sh 2>&1)"; FRESH_RC=$?
  printf '%s\n' "$FRESH_OUT"
  if (( FRESH_RC != 0 )); then
    FAILED+=("4) بياتُ الحجوزات (فرعٌ محذوفٌ وحجزٌ نشط)")
  elif [[ "$FRESH_OUT" == *"جزئي"* ]]; then
    SKIPPED+=("4) بياتُ الحجوزات — جزئيٌّ: لم يُسأل المستودعُ عن كلِّ فرع")
  else
    PASSED+=("4) بياتُ الحجوزات (فرعٌ محذوفٌ وحجزٌ نشط)")
  fi
else
  SKIPPED+=("4) بياتُ الحجوزات — السكربت غير موجود")
fi

# ── 5) هدفُ طلبِ الدمج (M0-17) ───────────────────────────────────────────
# لا يُحتاج git range: السؤالُ **إلى أين يُدمَج هذا؟** لا عن فرقِ التزامَين. ويُفرَّق
# في الاحتسابِ بين ثلاثةِ مخارجَ لا مخرجَين، لأنّ الخلطَ يُجمِّل أو يُشيع تنبيهاً كاذباً:
#   • رمزُ خروجٍ ≠ 0            → فشلٌ.
#   • المخرجُ فيه «جزئي»        → تخطٍّ: هناك هدفٌ ولم يُسأل المستودعُ عنه.
#   • المخرجُ فيه «لا ينطبق»    → مرورٌ بوسمٍ صريح: ليس سياقَ طلبِ دمجٍ أصلاً (خطُّ
#     `main` أو تشغيلٌ يدويّ) — فليس ذلك نقصاً في الفحصِ ولا يُخفى في الخلاصة.
if [[ -f scripts/checks/validate-mr-target.sh ]]; then
  hdr "5) هدفُ طلبِ الدمج (فرعٌ مدموجٌ أو محذوفٌ يُعلِق العمل)"
  MRT_OUT="$(bash scripts/checks/validate-mr-target.sh 2>&1)"; MRT_RC=$?
  printf '%s\n' "$MRT_OUT"
  if (( MRT_RC != 0 )); then
    FAILED+=("5) هدفُ طلبِ الدمج (فرعٌ مدموجٌ أو محذوفٌ يُعلِق العمل)")
  elif [[ "$MRT_OUT" == *"جزئي"* ]]; then
    SKIPPED+=("5) هدفُ طلبِ الدمج — جزئيٌّ: لم يُسأل المستودعُ عن الهدف")
  elif [[ "$MRT_OUT" == *"لا ينطبق"* ]]; then
    PASSED+=("5) هدفُ طلبِ الدمج (لا ينطبق — ليس سياقَ طلبِ دمج)")
  else
    PASSED+=("5) هدفُ طلبِ الدمج (فرعٌ مدموجٌ أو محذوفٌ يُعلِق العمل)")
  fi
else
  SKIPPED+=("5) هدفُ طلبِ الدمج — السكربت غير موجود")
fi

# ── 6) الأسرار ──────────────────────────────────────────────────────────
if [[ -f scripts/checks/scan-secrets.sh ]]; then
  run_check "6) فحص الأسرار" bash scripts/checks/scan-secrets.sh
else
  SKIPPED+=("6) فحص الأسرار — السكربت غير موجود")
fi

# ── 7) عزلُ DDL في اختباراتِ التكامل (M0-03) ─────────────────────────────
# لا يُحتاج git ولا قاعدةَ بيانات: السؤالُ **أيضمن الإعدادُ ألّا يجري ملفّانِ**
# يُسقطان جداولَ القاعدةِ نفسِها معاً. ويُفرَّق في الاحتسابِ بين ثلاثةِ مخارجَ كما
# في الفحصَين 4 و5: فشلٌ (رمزٌ ≠ 0) · «لا ينطبق» مرورٌ بوسمٍ صريحٍ (لا خدمةَ لها
# ملفّانِ أصلاً — وليس ذلك نقصاً في الفحص) · وإلّا مرورٌ كامل. ولا وجهَ لـ«جزئي»
# هنا: الفحصُ يقرأ ملفّاتِ الإعدادِ من القرصِ فلا يبقى موضعُ جهلٍ يُعلَن.
if [[ -f scripts/checks/validate-integration-isolation.sh ]]; then
  hdr "7) عزلُ DDL في اختباراتِ التكامل"
  ISO_OUT="$(bash scripts/checks/validate-integration-isolation.sh 2>&1)"; ISO_RC=$?
  printf '%s\n' "$ISO_OUT"
  if (( ISO_RC != 0 )); then
    FAILED+=("7) عزلُ DDL في اختباراتِ التكامل")
  elif [[ "$ISO_OUT" == *"لا ينطبق"* ]]; then
    PASSED+=("7) عزلُ DDL (لا ينطبق — لا خدمةَ بملفَّين تكامليَّين)")
  else
    PASSED+=("7) عزلُ DDL في اختباراتِ التكامل")
  fi
else
  SKIPPED+=("7) عزلُ DDL — السكربت غير موجود")
fi

# ── 8) CI مانعٌ لا مُجمِّل (M0-04) ───────────────────────────────────
# السّؤالُ: **أيُسقِطُ الخطُّ دفعاً معيباً؟** لا: أيُجمِّلُ؟ والفحصُ يقرأ النّصوصَ:
# مدخلٌ موحَّدٌ مُستدعًَ · لا قائمةَ إلزامٍ مضمَّنةً · لا allow_failure صامتٌ · لا
# حارسَ يتيمٍ. **وحدُّه المُعلَنُ** أنّه لا يسأل GitLab عن
# `only_allow_merge_if_pipeline_succeeds` — وهو إعدادٌ خارجَ المستودع، وكان
# `false` مقيساً 2026-08-27. فيُحتسبُ هذا الفحصُ **جزئيّاً دائماً**: إعدادُ
# المستودعِ متّسقٌ، ورفضُ الدمجِ عندَ الإخفاقِ غيرُ مُفعَّلٍ ولا يُدَّعى خلافُه
# (docs/00-rules/VERIFY_COMMAND.md §7). وتجميلُه نجاحاً كاملاً كان يُوهِمُ أنّ
# البوّابةَ تمنعُ الدمجَ وهي لا تملكُ ذلك.
if [[ -f scripts/checks/validate-ci-mandatory.sh ]]; then
  hdr "8) CI مانعٌ لا مُجمِّل (M0-04)"
  CIM_OUT="$(bash scripts/checks/validate-ci-mandatory.sh 2>&1)"; CIM_RC=$?
  printf '%s\n' "$CIM_OUT"
  # ومنذ M0-25 لم يعُدِ الشقُّ الثاني مسكوتاً عنه: `validate-merge-blocking.sh`
  # يقيسُ ما يملكُ المستودعُ إثباتَه — **مطابقةَ وظائفِ الخطِّ بالسياقاتِ المطلوبةِ**
  # في لقطةٍ مؤرَّخةٍ، و`strict`/`enforce_admins`، **وبرهانَ رفضٍ 405 بمرجعٍ حَيٍّ**.
  # ويبقى `2` (جزئيٌّ مُعلَنٌ) ما دامت اللقطةُ مؤرَّخةً لا حيّةً: **التخطّي لا يُجمَّل
  # نجاحاً، والنجاحُ لا يُدَّعى بلا سؤالٍ حَيٍّ.**
  MB_RC=0
  if [[ -f scripts/checks/validate-merge-blocking.sh ]]; then
    MB_OUT="$(bash scripts/checks/validate-merge-blocking.sh 2>&1)"; MB_RC=$?
    printf '%s\n' "$MB_OUT"
  else
    MB_RC=3
  fi
  if (( CIM_RC != 0 )); then
    FAILED+=("8) CI مانعٌ لا مُجمِّل")
  elif (( MB_RC == 1 )); then
    FAILED+=("8) CI مانعٌ — الحمايةُ المُعلَنةُ لا تطابقُ الخطَّ")
  elif (( MB_RC == 0 )); then
    PASSED+=("8) CI مانعٌ — الحمايةُ مطابقةٌ ومُبرهَنةٌ ومسؤولةٌ حيّاً")
  elif (( MB_RC == 2 )); then
    # M0-29: لا يُعادُ صوغُ سببِ الجزئيّةِ هنا. كانَ هذا السطرُ يقولُ «ولم تُسأل
    # الواجهةُ حيّاً» **مهما كانَ سببُ الـ2**، فلمّا سُئلت الواجهةُ وأجابت بالنفيِ
    # صارَ السطرُ **كذباً مُطمئنّاً** في الخلاصةِ التي يُستشهَدُ بها. فالسببُ يُقرأُ
    # من نصِّ الحارسِ نفسِه — حقيقةٌ واحدةٌ لا حقيقتانِ.
    MB_WHY="$(printf '%s\n' "$MB_OUT" \
      | sed $'s/\033\\[[0-9;]*m//g' \
      | grep -m1 '⊘ منعُ الدمجِ' \
      | sed 's/.*⊘ منعُ الدمجِ — //' || true)"
    SKIPPED+=("8) CI مانعٌ — جزئيٌّ: ${MB_WHY:-الأبوابُ نجحت على لقطةٍ مؤرَّخةٍ، ولم تُسأل الواجهةُ حيّاً}")
  else
    SKIPPED+=("8) CI مانعٌ — جزئيٌّ: حارسُ منعِ الدمجِ غيرُ موجودٍ")
  fi
else
  SKIPPED+=("8) CI مانعٌ — السكربت غير موجود")
fi

# ── 9) تدقيقُ الاعتماديات (M0-06) ────────────────────────────────────────
# السّؤالُ: **أفي المستودعِ اعتماديةٌ معروفةُ الثغرةِ تمرُّ صامتةً؟** والجوابُ
# بأربعةِ أبوابٍ: شجرةُ الإنتاجِ نقيّةٌ بلا استثناءٍ · كلُّ ثغرةٍ في أدواتِ
# التطويرِ مُعلَنةٌ بمالكٍ ومهلةٍ ساريةٍ · مديرُ الحزمِ مثبَّتٌ · كلُّ تثبيتٍ
# قسريٍّ مُبرَّرٌ. ويُفرّق في الاحتسابِ بين ثلاثةِ مخارجَ: فشلٌ (رمزٌ 1) ·
# **جزئيٌّ مُعلَنٌ (رمزٌ 2)** حين لا يُسأل المُسجَّلُ لغيابِ pnpm أو الشبكةِ —
# فالأبوابُ النصّيّةُ وحدَها جرت · وإلّا مرورٌ كامل. ولا يُجمَّل التخطّي نجاحاً:
# تدقيقٌ لم يسأل أحداً ليس تدقيقاً.
if [[ -f scripts/checks/validate-dependency-audit.sh ]]; then
  hdr "9) تدقيقُ الاعتماديات والثغرات (M0-06)"
  DEP_OUT="$(bash scripts/checks/validate-dependency-audit.sh 2>&1)"; DEP_RC=$?
  printf '%s\n' "$DEP_OUT"
  if (( DEP_RC == 1 )); then
    FAILED+=("9) تدقيقُ الاعتماديات والثغرات")
  elif (( DEP_RC == 2 )); then
    SKIPPED+=("9) تدقيقُ الاعتماديات — جزئيٌّ: لم يُسأل مُسجَّلُ npm (لا pnpm أو لا شبكة)")
  elif (( DEP_RC != 0 )); then
    FAILED+=("9) تدقيقُ الاعتماديات — رمزٌ غيرُ متوقّعٍ ($DEP_RC)")
  else
    PASSED+=("9) تدقيقُ الاعتماديات والثغرات")
  fi
else
  SKIPPED+=("9) تدقيقُ الاعتماديات — السكربت غير موجود")
fi

# ── 10) سجلُّ المخاطرِ والاستثناءات (M0-07) ─────────────────────────
# السّؤالُ: **أفي المستودعِ خطرٌ مقبولٌ بلا مالكٍ أو بلا تاريخِ مراجعة؟**
# وبأربعةِ أبوابٍ: الصّيغةُ والمرجعُ الحَيُّ · المهلةُ تنتهي · لا استثناءَ
# في §11 بلا خطرٍ مُسجَّلٍ · ولا سجلَّ يتيماً لا يُحال إليه. والفحصُ نصّيٌّ
# بحتٌ لا يسأل شبكةً ولا يقرأ كوداً، فلا تخطّيَ له أصلاً: مرورٌ أو إخفاق.
if [[ -f scripts/checks/validate-risk-register.sh ]]; then
  hdr "10) سجلُّ المخاطرِ والاستثناءات (M0-07)"
  if RISK_OUT="$(bash scripts/checks/validate-risk-register.sh 2>&1)"; then
    printf '%s\n' "$RISK_OUT"
    PASSED+=("10) سجلُّ المخاطرِ والاستثناءات")
  else
    printf '%s\n' "$RISK_OUT"
    FAILED+=("10) سجلُّ المخاطرِ والاستثناءات")
  fi
else
  SKIPPED+=("10) سجلُّ المخاطر — السكربت غير موجود")
fi

# ── 11) الأساسُ الآليُّ للبيئةِ والاختبارات (M0-08) ─────────────────
# السّؤالُ: **أينحدرُ المستودعُ في صمتٍ؟** فأرتفاكتٌ لا يقيس عدَّاداً يتكرَّر
# لأنّه لا يقول شيئاً — لو حُذفَ مئةُ اختبارٍ لبقيَ أخضرَ متطابقاً. وبأربعةِ
# أبوابٍ: الصّيغةُ وبصمةٌ متّسقةٌ ذاتيّاً · لا انحدارَ بين الحيِّ والمُلتزَمِ ·
# التكرارُ يُبرهَن بالطفرةِ لا يُدَّعى · ولا أساسَ يتيماً بلا صيغةٍ موثَّقةٍ
# وأرقامٍ مقيسةٍ. ولا تخطّيَ له: قياسٌ نصّيٌّ محلّيٌّ بلا شبكةٍ — مرورٌ أو إخفاق.
if [[ -f scripts/checks/validate-baseline.sh ]]; then
  hdr "11) الأساسُ الآليُّ للبيئةِ والاختبارات (M0-08)"
  if BASE_OUT="$(bash scripts/checks/validate-baseline.sh 2>&1)"; then
    printf '%s\n' "$BASE_OUT"
    PASSED+=("11) الأساسُ الآليُّ للبيئةِ والاختبارات")
  else
    printf '%s\n' "$BASE_OUT"
    FAILED+=("11) الأساسُ الآليُّ للبيئةِ والاختبارات")
  fi
else
